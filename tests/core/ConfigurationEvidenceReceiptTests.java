import io.github.niwantha33.zew.core.ConfigurationEvidenceReceipt;
import io.github.niwantha33.zew.core.ConfigurationEvidenceReceipt.State;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.FileTime;
import java.time.Instant;

/** Behavioral CS-01 acceptance fixtures; no build/flash/network access. */
public final class ConfigurationEvidenceReceiptTests {
    private static int checks;
    private static void check(boolean condition, String message) {
        if (!condition) throw new AssertionError(message);
        checks++;
    }
    private record Fixture(Path app, Path build, Path conf, Path overlay,
                           Path board, Path dts, Path generatedConfig) {}
    private static Fixture fixture() throws Exception {
        Path root = Files.createTempDirectory("zew config provenance ");
        Path app = Files.createDirectories(root.resolve("project space"));
        Path build = Files.createDirectories(root.resolve("debug build"));
        Path zephyr = Files.createDirectories(build.resolve("zephyr"));
        Path conf = app.resolve("prj.conf");
        Path board = app.resolve("sample-board.dtsi");
        Path overlay = app.resolve("app.overlay");
        Path dts = zephyr.resolve("zephyr.dts");
        Path generated = zephyr.resolve(".config");
        Files.writeString(app.resolve("CMakeLists.txt"),
                "cmake_minimum_required(VERSION 3.20.0)\n", StandardCharsets.UTF_8);
        Files.writeString(conf, "CONFIG_GPIO=y\n", StandardCharsets.UTF_8);
        Files.writeString(board, "/ { chosen {}; };\n", StandardCharsets.UTF_8);
        Files.writeString(overlay, "&gpio0 { status = \"okay\"; };\n", StandardCharsets.UTF_8);
        Files.writeString(build.resolve("CMakeCache.txt"),
                "BOARD:STRING=example/qualifier\n"
                + "CONF_FILE:STRING=prj.conf\n"
                + "DTC_OVERLAY_FILE:STRING=app.overlay\n", StandardCharsets.UTF_8);
        // Make-style depfile escapes literal spaces, as generated by GCC/DTC.
        String make = "zephyr/zephyr.dts: "
                + board.toString().replace(" ", "\\ ") + " "
                + overlay.toString().replace(" ", "\\ ") + "\n";
        Files.writeString(zephyr.resolve("zephyr.dts.d"), make, StandardCharsets.UTF_8);
        Files.writeString(generated, "CONFIG_GPIO=y\n", StandardCharsets.UTF_8);
        Files.writeString(dts, "/dts-v1/;\n/ { };\n", StandardCharsets.UTF_8);
        return new Fixture(app, build, conf, overlay, board, dts, generated);
    }
    private static State state(Fixture f, String board, String profile) {
        return ConfigurationEvidenceReceipt.inspect(f.app(), f.build(), board, profile).state();
    }
    private static ConfigurationEvidenceReceipt.Result capture(Fixture f) throws Exception {
        return ConfigurationEvidenceReceipt.capture(f.app(), f.build(),
                "example/qualifier", "debug");
    }
    public static void main(String[] args) throws Exception {
        var f = fixture();
        check(state(f, "example/qualifier", "debug") == State.UNVERIFIED,
                "preexisting generated build without receipt is unverified, not current");
        var captured = capture(f);
        check(captured.state() == State.CURRENT && captured.sourceCount() >= 4
                && captured.configSha256().matches("[0-9a-f]{64}")
                && captured.devicetreeSha256().matches("[0-9a-f]{64}"),
                "receipt captures selected active Kconfig/DTS inputs and generated outputs");
        check(state(f, "example/qualifier", "debug") == State.CURRENT,
                "capture can be verified without compiler or network");
        var receipt = ConfigurationEvidenceReceipt.receiptPath(f.build());
        check(Files.isRegularFile(receipt)
                && !Files.exists(f.app().resolve(".zew"))
                && Files.readString(receipt).contains("ZEW-CONFIG-RECEIPT-1"),
                "only build-local receipt written; application left untouched");

        Files.writeString(f.conf(), "CONFIG_GPIO=n\n", StandardCharsets.UTF_8);
        check(state(f, "example/qualifier", "debug") == State.CHANGED,
                "changing only prj.conf invalidates recorded build even with same mtime");
        Files.writeString(f.conf(), "CONFIG_GPIO=y\n", StandardCharsets.UTF_8);
        check(state(f, "example/qualifier", "debug") == State.CURRENT,
                "restoring exact bytes restores matching hashes");
        FileTime before = Files.getLastModifiedTime(f.conf());
        Files.setLastModifiedTime(f.conf(), FileTime.from(Instant.now().plusSeconds(200)));
        check(state(f, "example/qualifier", "debug") == State.CURRENT,
                "metadata-only timestamp change does not produce false stale finding");
        Files.setLastModifiedTime(f.conf(), before);

        Files.writeString(f.board(), "/ { chosen { test = <1>; }; };\n");
        check(state(f, "example/qualifier", "debug") == State.CHANGED,
                "changing an included DTSI marks the captured build stale");
        Files.writeString(f.board(), "/ { chosen {}; };\n");
        check(state(f, "example/qualifier", "debug") == State.CURRENT,
                "restored included source matches");
        Files.writeString(f.overlay(), "&gpio0 { status = \"disabled\"; };\n");
        check(state(f, "example/qualifier", "debug") == State.CHANGED,
                "changing active overlay marks build stale");
        Files.writeString(f.overlay(), "&gpio0 { status = \"okay\"; };\n");

        var unused = f.app().resolve("unused.overlay");
        Files.writeString(unused, "&uart1 { status = \"okay\"; };\n");
        check(state(f, "example/qualifier", "debug") == State.CURRENT,
                "inactive overlay does not invalidate selected build");
        Files.writeString(unused, "&uart1 { status = \"disabled\"; };\n");
        check(state(f, "example/qualifier", "debug") == State.CURRENT,
                "inactive candidate changes remain unrelated to active build inputs");
        check(state(f, "other-board", "debug") == State.CHANGED
                && state(f, "example/qualifier", "release") == State.CHANGED,
                "board qualifier and independent build profile cannot reuse receipt");
        Files.writeString(f.generatedConfig(), "CONFIG_GPIO=n\n");
        check(state(f, "example/qualifier", "debug") == State.CHANGED,
                "changing generated Kconfig invalidates receipt");
        Files.writeString(f.generatedConfig(), "CONFIG_GPIO=y\n");
        Files.writeString(f.dts(), "/dts-v1/;\n/ { status = \"okay\"; };\n");
        check(state(f, "example/qualifier", "debug") == State.CHANGED,
                "changing generated DTS invalidates receipt");
        Files.writeString(f.dts(), "/dts-v1/;\n/ { };\n");
        check(state(f, "example/qualifier", "debug") == State.CURRENT,
                "restoring output bytes matches original receipt");

        Files.writeString(receipt, "INVALID\n");
        check(state(f, "example/qualifier", "debug") == State.UNVERIFIED,
                "malformed receipt never proves current build");
        capture(f);
        Files.delete(receipt);
        check(state(f, "example/qualifier", "debug") == State.UNVERIFIED,
                "removed receipt reverts to unverified");
        Files.delete(f.dts());
        check(state(f, "example/qualifier", "debug") == State.NO_BUILD,
                "missing generated DTS never presents a current build");

        var cmakeRegenerated = fixture();
        Files.setLastModifiedTime(cmakeRegenerated.app().resolve("CMakeLists.txt"),
                FileTime.from(Instant.now().plusSeconds(3600)));
        Files.setLastModifiedTime(cmakeRegenerated.build().resolve("CMakeCache.txt"),
                FileTime.from(Instant.now().plusSeconds(7200)));
        check(capture(cmakeRegenerated).state() == State.CURRENT,
                "a newer CMakeLists with regenerated CMake cache must not require a rewritten DTS");

        var cmakeNotRegenerated = fixture();
        Files.setLastModifiedTime(cmakeNotRegenerated.app().resolve("CMakeLists.txt"),
                FileTime.from(Instant.now().plusSeconds(3600)));
        check(capture(cmakeNotRegenerated).state() == State.UNVERIFIED,
                "CMakeLists changed after CMake cache remains unverified");

        var lateSource = fixture();
        Files.setLastModifiedTime(lateSource.conf(),
                FileTime.from(Instant.now().plusSeconds(3600)));
        check(capture(lateSource).state() == State.UNVERIFIED,
                "source touched after generated .config must not be certified as current");

        var incomplete = fixture();
        Files.delete(incomplete.build().resolve("zephyr/zephyr.dts.d"));
        check(capture(incomplete).state() == State.UNVERIFIED
                && state(incomplete, "example/qualifier", "debug") == State.UNVERIFIED,
                "missing DTS input dependency evidence forces unverified, not current");
        check(ConfigurationEvidenceReceipt.inspect(incomplete.app(), incomplete.build(),
                "example/qualifier", "debug").detail().contains("DTS dependency file is unavailable"),
                "persistent partial receipts retain a specific reason for the Studio to display");
        check(Files.readString(incomplete.conf()).equals("CONFIG_GPIO=y\n"),
                "collecting partial evidence never edits configuration sources");

        System.out.println("PASS configuration provenance receipt: " + checks);
    }
}
