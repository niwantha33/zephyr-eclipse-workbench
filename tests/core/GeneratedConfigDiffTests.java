import io.github.niwantha33.zew.core.GeneratedConfigDiff;
import io.github.niwantha33.zew.core.GeneratedConfigHistory;
import java.nio.file.Files;
import java.nio.file.Path;

public final class GeneratedConfigDiffTests {
    private static void ok(boolean value, String message) {
        if (!value) throw new AssertionError(message);
    }

    public static void main(String[] args) throws Exception {
        String oldConfig = "#\n# Kernel\n#\nCONFIG_THREADS=y\n"
                + "# CONFIG_THREAD_NAME is not set\nCONFIG_STACK_SIZE=1024\n"
                + "#\n# Drivers\n#\nCONFIG_SPI=y\nCONFIG_I2C=y\n";
        String newConfig = "#\n# Kernel\n#\nCONFIG_THREADS=y\n"
                + "CONFIG_THREAD_NAME=y\nCONFIG_STACK_SIZE=2048\n"
                + "#\n# Drivers\n#\nCONFIG_SPI=y\nCONFIG_ADC=y\n";
        var result = GeneratedConfigDiff.compare(oldConfig, newConfig);
        ok(result.hasBaseline() && result.added() == 1 && result.changed() == 2
                && result.removed() == 1 && result.unchanged() == 2,
                "detect added, changed, removed and unchanged symbols");
        ok(result.sections().stream().anyMatch(s -> s.heading().equals("Kernel")
                && s.entries().stream().anyMatch(e -> e.symbol().equals("CONFIG_THREAD_NAME")
                && "n".equals(e.previous()) && "y".equals(e.current())
                && e.change() == GeneratedConfigDiff.Change.CHANGED)),
                "unset Zephyr boolean is n rather than missing; comment sections retained");
        ok(result.sections().stream().flatMap(s -> s.entries().stream())
                .anyMatch(e -> e.symbol().equals("CONFIG_I2C")
                && e.change() == GeneratedConfigDiff.Change.REMOVED && e.current() == null),
                "removed symbol is absent rather than disabled");
        var withoutBaseline = GeneratedConfigDiff.compare(null, newConfig);
        ok(!withoutBaseline.hasBaseline() && withoutBaseline.differences() == 0,
                "no baseline must not paint every symbol as added");
        boolean rejected = false;
        try { GeneratedConfigDiff.compare("", "CONFIG_A=y\nCONFIG_A=n\n"); }
        catch (IllegalArgumentException expected) { rejected = true; }
        ok(rejected, "duplicate generated options are rejected, not silently compared");

        Path directory = Files.createTempDirectory("zew-config-history-");
        try {
            Path output = directory.resolve("zephyr");
            Files.createDirectories(output);
            Files.writeString(output.resolve(".config"), oldConfig);
            String captured = GeneratedConfigHistory.capture(directory);
            Files.writeString(output.resolve(".config"), newConfig);
            GeneratedConfigHistory.commit(directory, captured);
            ok(GeneratedConfigDiff.read(GeneratedConfigHistory.baseline(directory)).equals(oldConfig),
                    "successful-build history preserves the previous generated bytes");
            ok(Files.readString(output.resolve(".config")).equals(newConfig),
                    "history never modifies the authoritative current .config");
            GeneratedConfigHistory.commit(directory, null);
            ok(!Files.exists(GeneratedConfigHistory.baseline(directory)),
                    "first build with no previous configuration clears stale history");
        } finally {
            try (var files = Files.walk(directory)) {
                files.sorted(java.util.Comparator.reverseOrder()).forEach(p -> {
                    try { Files.deleteIfExists(p); } catch (Exception error) {
                        throw new AssertionError(error);
                    }
                });
            }
        }
        System.out.println("GeneratedConfigDiffTests OK");
    }
}
